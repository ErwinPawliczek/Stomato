REPO_ROOT = Path(__file__).resolve().parent.parent
CASES_PATH = REPO_ROOT / "data" / "validation" / "cases.yaml"
RESULTS_PATH = REPO_ROOT / "data" / "validation" / "results.json"
DOC_PATH = REPO_ROOT / "docs" / "validation.md"


def _case_files() -> list[Path]:
    """Every reference-case file: the root ``cases.yaml`` plus per-family ``cases*.yaml``.

    Data sweeps (spec T-11) add ``data/validation/<family>/cases.yaml``; entries whose
    ``package`` is ``pending:<id>`` name a catalogue row that is not registered yet and are
    skipped by :func:`_load_cases` until the row lands.
    """
    return sorted((REPO_ROOT / "data" / "validation").glob("**/cases*.yaml"))


#: Package expansion of ``package: all`` — the three cubic packages. NRTL runs only where the
#: reference system is an activity-coefficient system (its cases name ``nrtl`` directly).
CUBIC_PACKAGES = ("pr", "srk", "pr78")

#: Tolerances fixed by the spec P1-05 before any result was seen. ``cases.yaml`` may override
#: per property (the NRTL cases do: bubble 2 %, y 0.02 abs).
TOLERANCE_POLICY: dict[str, float] = {
    "rho_V": 0.03,  # cubic vs reference vapour density
    "rho_L": 0.08,  # liquid density — known cubic weakness
    "Cp": 0.05,
    "bubble_P": 0.03,
    "dew_P": 0.03,
    "bubble_T": 0.005,  # isobaric analogue of the 3 % bubble-P tolerance
    "K": 0.05,
    "vapor_comp": 0.02,  # absolute
    "liquid_comp": 0.02,  # absolute
}

#: Properties compared on absolute error (compositions) vs relative error (everything else).
ABSOLUTE_ERROR_PROPERTIES = frozenset({"vapor_comp", "liquid_comp"})

HEADER = """\
# P1-05 property-validation reference cases (spec: specs/backend/P1-05-property-validation-harness.md).
#
# Sections:
#   pure_cases            -- pure-fluid saturation references. `expected` is machine-generated by
#     `uv run python scripts/validate_properties.py --regen-coolprop` (source "coolprop:<fluid>",
#     CoolProp version recorded in meta.coolprop_version). Regenerated, never hand-typed.
#   binary_cases          -- literature VLE points, hand-typed from the cited table/page with the
#     retrieval date. Never fetched or regenerated by the script.
#   multicomponent_cases  -- chart-read K values for the slice inlet.
#
# Units: T [K], P [Pa abs], density [kg/m3], Cp [J/(mol K)], compositions [mole fraction].
#
# Tolerances are fixed by the spec BEFORE looking at results (docs/validation.md repeats them):
#   density 3 % vapour / 8 % liquid (known cubic weakness), Cp 5 %, bubble/dew P 3 %, K 5 %;
#   NRTL MeOH/H2O bubble 2 %, y 0.02 abs. Isobaric bubble-temperature tolerance 0.5 % relative
#   (the isobaric analogue of the 3 % bubble-P tolerance; see docs/validation.md). Composition
#   comparisons are absolute, 0.02. A case may override a tolerance per property via `tolerance`.
"""


@dataclasses.dataclass(frozen=True)
class Case:
    """One reference case from ``cases.yaml`` (schema in the file header)."""

    id: str
    package: str
    components: list[str]
    z: dict[str, float]
    source: str
    expected: dict[str, Any]
    T: float | None = None
    P: float | None = None
    tolerance: dict[str, float] = dataclasses.field(default_factory=dict)
    note: str = ""
    # pure-fluid scaffolding (source "coolprop:<fluid>" cases)
    fluid: str = ""
    coolprop_fluid: str = ""
    # cases.yaml section the case came from (the audit's L1/L2 classification)
    section: str = ""


@dataclasses.dataclass(frozen=True)
class Row:
    """One comparison result: case x package x property (the results.json row, spec shape)."""

    case: str
    package: str
    property: str
    expected: float | None
    got: float | None
    rel_err: float | None  # relative error, or absolute error for composition properties
    passed: bool


@cache
def _package(name: str) -> Thermo:
    """Build (and cache) a thermo package instance through the registry."""
    return cast(Thermo, registry.create("thermo", name))


def packages_for(case: Case) -> tuple[str, ...]:
    """Expand ``package: all`` to the cubic packages; pass explicit names through."""
    if case.package == "all":
        return CUBIC_PACKAGES
    return (case.package,)


def xfail_reason(case: Case, failed_props: frozenset[str]) -> str | None:
    """Assessment for a case whose comparisons failed, or None when it must go red.

    Each rule matches one failure family observed on the first run AND guards the failing
    properties, so a future case failing on a different property is not silently classified
    here — it fails the test and forces a fresh assessment. Used by the reference-case tests
    (dynamic xfail) and by ``write_doc`` (assessment section).
    """
    if case.id.startswith("pure-") and failed_props <= {"rho_L", "rho_V", "Cp"}:
        return (
            "cubic saturation properties beyond tolerance vs the CoolProp reference EOS "
            "(known cubic EOS limitation, worst near Tc; assessed in docs/validation.md)"
        )
    if case.id.startswith("meohh2o-"):
        return (
            "NRTL databank MeOH/H2O parameters do not reproduce the 1927/1929 isotherms within "
            "2 % bubble P / 0.02 abs y (databank limitation; assessed in docs/validation.md)"
        )
    if case.id.startswith(("c1c3-", "c1co2-")) and failed_props <= {"bubble_P", "vapor_comp"}:
        return (
            "k_ij=0 cubic bubble pressure / vapour composition just beyond tolerance near the "
            "mixture critical region (model limitation; assessed in docs/validation.md)"
        )
    if case.id == "c1h2o-410.9K-13.10MPa":
        return (
            "cubic two-phase flash yields an unphysical water/methane phase split at 13 MPa, so "
            "the aqueous methane solubility is not representable (flagged for thermo investigation)"
        )
    if case.id.startswith("ng-dew-morch-") and failed_props <= {"dew_P"}:
        return (
            "dew pressures of the asymmetric C1/C2/nC5 synthetic natural gas ternary run 10-35 % "
            "above the Mørch et al. (2006) cooled-mirror measurements under databank/zero k_ij "
            "(model limitation, issue #130; assessed in docs/validation.md)"
        )
    if case.id == "slice-inlet-K-500psia-300K":
        return (
            "chart-read K values (5-7 % reading precision) vs k_ij=0 cubic K "
            "(data + model limitation; assessed in docs/validation.md)"
        )
    return None


def _load_cases() -> list[Case]:
    import yaml

    cases: list[Case] = []
    for path in _case_files():
        raw = yaml.safe_load(path.read_text())
        for section in ("pure_cases", "binary_cases", "multicomponent_cases"):
            for entry in raw.get(section) or []:
                if str(entry.get("package", "all")).startswith("pending:"):
                    # Catalogue row not registered yet (T-02..T-07 adapter specs): the data
                    # sweep commits the cases ahead of the model; skip until the id lands.
                    continue
                case = Case(
                    id=str(entry["id"]),
                    package=str(entry.get("package", "all")),
                    components=list(entry.get("components", [])),
                    z={k: float(v) for k, v in entry["z"].items()},
                    source=str(entry["source"]),
                    expected=dict(entry.get("expected") or {}),
                    T=float(entry["T"]) if entry.get("T") is not None else None,
                    P=float(entry["P"]) if entry.get("P") is not None else None,
                    tolerance={k: float(v) for k, v in (entry.get("tolerance") or {}).items()},
                    note=str(entry.get("note", "")),
                    fluid=str(entry.get("fluid", "")),
                    coolprop_fluid=str(entry.get("coolprop_fluid", "")),
                    section=section,
                )
                cases.append(case)
    return cases


def _tolerance(case: Case, prop: str) -> float:
    return case.tolerance.get(prop, TOLERANCE_POLICY[prop])


def _row(case: Case, pkg: str, prop: str, expected: float, got: float | None) -> Row:
    """Build one comparison row; ``got`` None means the package could not produce a value."""
    tol = _tolerance(case, prop)
    if got is None:
        return Row(case.id, pkg, prop, expected, None, None, False)
    err = abs(got - expected) if prop in ABSOLUTE_ERROR_PROPERTIES else abs(got - expected) / abs(expected)
    return Row(case.id, pkg, prop, expected, got, err, err <= tol)


def _water_rich_liquid(state: Any) -> dict[str, float] | None:
    """Composition of the water-rich liquid phase of a flash, if one exists.

    Prefers the aqueous phase label; falls back to the non-vapour phase with the largest
    H2O mole fraction (cubic packages label all liquids hc_liquid today).
    """
    liquids = [p for p in state.phases if p.kind != PhaseKind.VAPOR]
    if not liquids:
        return None
    aqueous = [p for p in liquids if p.kind == PhaseKind.AQUEOUS]
    pool = aqueous or liquids
    composition = max(pool, key=lambda p: p.composition.get("H2O", 0.0)).composition
    return {str(k): float(v) for k, v in composition.items()}


def evaluate_case(case: Case, pkg: str) -> list[Row]:
    """Run one case through one package via the Thermo protocol only."""
    surf = _package(pkg)
    z, T, P, exp = case.z, case.T, case.P, case.expected
    rows: list[Row] = []

    def bubble() -> Any:
        if T is not None:
            return surf.bubble_point(z, T=T)
        assert P is not None
        return surf.bubble_point(z, P=P)

    if "bubble_P" in exp:
        assert T is not None, f"{case.id}: bubble_P comparison needs T"
        rows.append(_row(case, pkg, "bubble_P", float(exp["bubble_P"]), float(bubble().P)))
    if "bubble_T" in exp:
        assert P is not None, f"{case.id}: bubble_T comparison needs P"
        rows.append(_row(case, pkg, "bubble_T", float(exp["bubble_T"]), float(bubble().T)))
    if "dew_P" in exp:
        assert T is not None, f"{case.id}: dew_P comparison needs T"
        rows.append(_row(case, pkg, "dew_P", float(exp["dew_P"]), float(surf.dew_point(z, T=T).P)))
    if "vapor_comp" in exp:
        got_y = bubble().incipient_composition
        for cid, want in exp["vapor_comp"].items():
            rows.append(_row(case, pkg, "vapor_comp", float(want), float(got_y.get(cid, float("nan")))))
    if "liquid_comp" in exp:
        assert T is not None and P is not None, f"{case.id}: liquid_comp comparison needs T and P"
        state = surf.flash_pt(z, T, P, molar_flow=1.0)
        liq = _water_rich_liquid(state)
        for cid, want in exp["liquid_comp"].items():
            got = liq.get(cid) if liq else None
            rows.append(_row(case, pkg, "liquid_comp", float(want), float(got) if got is not None else None))
    if "K" in exp:
        assert T is not None and P is not None, f"{case.id}: K comparison needs T and P"
        kv = surf.k_values(z, T, P)
        for cid, want in exp["K"].items():
            got = kv.get(cid) if kv else None
            rows.append(_row(case, pkg, "K", float(want), float(got) if got is not None else None))
    # Pure-fluid saturated-phase properties at the reference saturation state (T, expected Psat).
    if {"rho_V", "rho_L", "Cp"} & exp.keys():
        assert T is not None, f"{case.id}: saturated-phase properties need T"
        p_sat = float(exp["bubble_P"])
        kind = PhaseKind.AQUEOUS if case.fluid == "H2O" else PhaseKind.HC_LIQUID
        if "rho_V" in exp:
            rows.append(
                _row(
                    case,
                    pkg,
                    "rho_V",
                    float(exp["rho_V"]),
                    float(surf.phase_props(z, T, p_sat, PhaseKind.VAPOR).density),
                )
            )
        if "rho_L" in exp:
            rows.append(
                _row(
                    case,
                    pkg,
                    "rho_L",
                    float(exp["rho_L"]),
                    float(surf.phase_props(z, T, p_sat, kind).density),
                )
            )
        if "Cp" in exp:
            rows.append(
                _row(case, pkg, "Cp", float(exp["Cp"]), float(surf.phase_props(z, T, p_sat, kind).cp))
            )
    return rows


def run_all(cases: list[Case]) -> list[Row]:
    """Evaluate every case against every named package; a package crash becomes failed rows."""
    rows: list[Row] = []
    for case in cases:
        if case.expected == {}:
            raise SystemExit(f"case {case.id} has no expected values — run --regen-coolprop first")
        for pkg in packages_for(case):
            try:
                rows.extend(evaluate_case(case, pkg))
            except SaftDependencyMissing as exc:
                # An absent optional backend (the saft rows' teqp extra) is an
                # environment fact, not a model failure: the case is skipped, visibly.
                print(f"SKIP: {case.id} on {pkg}: {exc}")
                continue
            except Exception as exc:  # noqa: BLE001 - reported as failed comparisons, never swallowed
                print(f"WARNING: {case.id} on {pkg} raised {type(exc).__name__}: {exc}")
                rows.extend(
                    Row(case.id, pkg, prop, float(case.expected[prop]), None, None, False)
                    for prop in case.expected
                    if prop in TOLERANCE_POLICY
                )
    return rows


# -- CoolProp regeneration (the one place CoolProp may be imported; spec gate) ----------------


def regen_coolprop() -> None:
    """Fill the ``pure_cases`` expected values from CoolProp, rewriting each case file.

    Every file matched by :func:`_case_files` is rewritten in place; each file's header
    comment block (everything before its ``meta:`` key) is preserved.
    """
    import CoolProp
    import yaml
    from CoolProp.CoolProp import PropsSI

    version = ""
    n_pure = 0
    for path in _case_files():
        text = path.read_text()
        raw = yaml.safe_load(text)
        for case in raw.get("pure_cases") or []:
            fluid = case["coolprop_fluid"]
            T = float(case["T"])
            version = CoolProp.__version__
            case["expected"] = {
                "bubble_P": PropsSI("P", "T", T, "Q", 0, fluid),
                "dew_P": PropsSI("P", "T", T, "Q", 1, fluid),
                "rho_V": PropsSI("D", "T", T, "Q", 1, fluid),
                "rho_L": PropsSI("D", "T", T, "Q", 0, fluid),
                "Cp": PropsSI("Cpmolar", "T", T, "Q", 0, fluid),
            }
            n_pure += 1
        raw["meta"]["coolprop_version"] = version
        head = re.split(r"(?m)^meta:", text, maxsplit=1)[0]
        path.write_text(head + yaml.dump(raw, sort_keys=False, default_flow_style=False, width=1000))
    print(f"regenerated {n_pure} pure cases in {len(_case_files())} files with CoolProp {version}")


# -- Reporting ---------------------------------------------------------------------------------


def _git_rev() -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
            timeout=10,
            cwd=REPO_ROOT,
        ).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return "unknown"


def environment() -> dict[str, Any]:
    import yaml as _yaml

    coolprop_version = (_yaml.safe_load(CASES_PATH.read_text()).get("meta") or {}).get(
        "coolprop_version", "unknown"
    )
    return {
        "generated": datetime.datetime.now(datetime.UTC).isoformat(timespec="seconds"),
        "python": platform.python_version(),
        "platform": platform.platform(),
        "git_rev": _git_rev(),
        "coolprop_version": coolprop_version,
    }


def print_report(rows: list[Row], sources: dict[str, str]) -> None:
    """Per-package stdout table: n, pass rate, worst 5 misses with their sources."""
    for pkg in sorted({r.package for r in rows}):
        sub = [r for r in rows if r.package == pkg]
        n_pass = sum(r.passed for r in sub)
        print(f"\n=== package {pkg}: {n_pass}/{len(sub)} pass ({100.0 * n_pass / len(sub):.1f} %) ===")
        worst = sorted((r for r in sub if not r.passed), key=lambda r: -(r.rel_err or 0.0))[:5]
        for r in worst:
            got = "n/a" if r.got is None else f"{r.got:.6g}"
            print(f"  {r.case} {r.property}: expected {r.expected:.6g} got {got} err {r.rel_err:.3g}")
            print(f"    source: {sources.get(r.case, 'n/a')}")
        if not worst:
            print("  (no failing comparisons)")


def _row_dict(r: Row) -> dict[str, object]:
    """Spec row shape; the dataclass field is ``passed`` because ``pass`` is a keyword."""
    return {
        "case": r.case,
        "package": r.package,
        "property": r.property,
        "expected": r.expected,
        "got": r.got,
        "rel_err": r.rel_err,
        "pass": r.passed,
    }


def write_results(rows: list[Row]) -> None:
    payload = {
        "environment": environment(),
        "summary": {
            "n_comparisons": len(rows),
            "n_pass": sum(r.passed for r in rows),
        },
        "rows": [_row_dict(r) for r in rows],
    }
    RESULTS_PATH.write_text(json.dumps(payload, indent=2) + "\n")


