#!/usr/bin/env python3
"""Property-validation harness (spec P1-05): every thermo package vs published references.

Runs every case in ``data/validation/cases.yaml`` through the named package(s) using only the
``Thermo`` protocol surface (``registry.create("thermo", ...)`` — no library bypass), compares
against the committed expected values with the tolerances fixed by the spec, writes
``data/validation/results.json`` (rows ``{case, package, property, expected, got, rel_err,
pass}`` plus environment metadata) and prints a per-package table: n cases, pass rate, worst
5 misses with their sources.

CoolProp-derived pure-fluid expected values are regenerated, not hand-typed::

    uv run python scripts/validate_properties.py --regen-coolprop

``docs/validation.md`` is regenerated from ``results.json``::

    uv run python scripts/validate_properties.py --write-doc

The script exits 0 even when cases fail: failing cases are *findings* (reported, assessed in
the PR), not script errors. ``tests/validation`` asserts per-case outcomes.

Reference values: literature points are hand-typed into ``cases.yaml`` from the cited source
with the retrieval date; the script never fetches. CoolProp values carry ``source: coolprop``
and the CoolProp version. CoolProp is imported only inside ``--regen-coolprop`` (spec gate).
"""

