def C_iso_eq4(D: float, d: float, rho: float, mu: float, qm: float, taps: str) -> float:
    """Independent ISO 5167-2:2003 eq. (4) implementation (spec equations).

    Written out from the spec, not via fluids: the closed-form check that
    ``C_Reader_Harris_Gallagher`` reduces to eq. (4) inside validity.
    """
    Re_D = 4.0 * qm / (math.pi * D * mu)
    beta = d / D
    A = (19000.0 * beta / Re_D) ** 0.8
    if taps == "corner":
        L1 = L2p = 0.0
    elif taps == "flange":
        L1 = L2p = 0.0254 / D
    else:  # D-D/2
        L1, L2p = 1.0, 0.47
    M2p = 2.0 * L2p / (1.0 - beta)
    C: float = (
        0.5961
        + 0.0261 * beta**2
        - 0.216 * beta**8
        + 0.000521 * (1e6 * beta / Re_D) ** 0.7
        + (0.0188 + 0.0063 * A) * beta**3.5 * (1e6 / Re_D) ** 0.3
        + (0.043 + 0.080 * math.exp(-10.0 * L1) - 0.123 * math.exp(-7.0 * L1))
        * (1.0 - 0.11 * A)
        * beta**4
        / (1.0 - beta**4)
        - 0.031 * (M2p - 0.8 * M2p**1.1) * beta**1.3
    )
    if D * 1000.0 < 71.12:
        C += 0.011 * (0.75 - beta) * (2.8 - D * 1000.0 / 25.4)
    return C


def assert_close(measured: float, expected: float, tol_rel: float = 1e-10) -> None:
    assert measured == pytest.approx(expected, rel=tol_rel)


def test_o1_liquid_flange() -> None:
    """Spec O1: liquid, D = 0.10226, d = 0.05, flange taps, qm = 10 kg/s."""
    r = orifice_dp(10.0, 0.10226, 0.05, 998.0, 1e-3, 5e5, None, "flange")
    assert_close(r["Re_D"], 124510.027844237)
    assert_close(r["C"], 0.605255904072185)
    assert_close(r["epsilon"], 1.0)
    assert_close(r["dP"], 33445.8129428092)
    assert_close(r["permanent_loss"], 24852.9608421957)
    # Independent eq. (4) cross-check (agrees with fluids to the last digit).
    assert_close(
        r["C"],
        C_iso_eq4(0.10226, 0.05, 998.0, 1e-3, 10.0, "flange"),
        tol_rel=1e-12,
    )


