"""Closed-form and adapter tests for the orifice R1 unit (spec O1-O3, S1, identity).

The expected values below are the spec's printed numbers, generated by an
independent ISO 5167-2 eq. (4)/(5) script (calc_orifice.py, its own
implementation, not fluids) and cross-checked here against a second
independent re-implementation of eq. (4) written out in this file. The
tolerance is 1e-10 relative (spec).

Hand computation, O1 (liquid, flange taps): D = 0.10226 m, d = 0.05 m,
qm = 10 kg/s, rho = 998 kg/m3, mu = 1e-3 Pa.s, P1 = 5e5 Pa.

    Re_D = 4*qm/(pi*D*mu) = 40/(pi*0.10226*1e-3) = 124510.027844237
    beta = d/D = 0.488949735967...
    L1 = L2' = 25.4 mm/D = 0.0254/0.10226 = 0.248388...
    eq. (4) with A = (19000*beta/Re_D)^0.8, M2' = 2*L2'/(1-beta)
        -> C = 0.605255904072185
    E = 1/sqrt(1-beta^4), A_o = pi/4*d^2, eps = 1 (liquid)
        dP = (qm/(C*E*A_o))^2/(2*rho) = 33445.8129428092 Pa
    permanent loss ratio (sqrt(1-beta^4(1-C^2)) - C beta^2)
                        / (sqrt(1-beta^4(1-C^2)) + C beta^2) * dP
        = 24852.9608421957 Pa
"""

