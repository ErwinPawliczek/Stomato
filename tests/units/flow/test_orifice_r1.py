"""Closed-form tests for the orifice R1 pure function (spec O1-O3).

The expected values below are the spec's printed numbers, generated by an
independent ISO 5167-2 eq. (4)/(5) script (calc_orifice.py, its own
implementation, not fluids) and cross-checked here against a second
independent re-implementation of eq. (4) written out in this file. The
tolerance is 1e-10 relative (spec).

Hand computation, O1 (liquid, flange taps): D = 0.10226 m, d = 0.05 m,
qm = 10 kg/s, rho = 998 kg/m3, mu = 1e-3 Pa.s, P1 = 5e5 Pa.

    Re_D = 4*qm/(pi*D*mu) = 40/(pi*0.10226*1e-3) = 124510.027844237
    beta = d/D = 0.488949735967...
    L1 = L2' = 25.4 mm/D = 0.0254/0.10226 = 0.248388...
    eq. (4) with A = (19000*beta/Re_D)^0.8, M2' = 2*L2'/(1-beta)
        -> C = 0.605255904072185
    E = 1/sqrt(1-beta^4), A_o = pi/4*d^2, eps = 1 (liquid)
        dP = (qm/(C*E*A_o))^2/(2*rho) = 33445.8129428092 Pa
    permanent loss ratio (sqrt(1-beta^4(1-C^2)) - C beta^2)
                        / (sqrt(1-beta^4(1-C^2)) + C beta^2) * dP
        = 24852.9608421957 Pa
"""

from __future__ import annotations

import math

import pytest

from ngdesign.units.flow.orifice_r1 import OrificeR1Error, orifice_dp


def C_iso_eq4(D: float, d: float, rho: float, mu: float, qm: float, taps: str) -> float:
    """Independent ISO 5167-2:2003 eq. (4) implementation (spec equations).

    Written out from the spec, not via fluids: the closed-form check that
    ``C_Reader_Harris_Gallagher`` reduces to eq. (4) inside validity.
    """
    Re_D = 4.0 * qm / (math.pi * D * mu)
    beta = d / D
    A = (19000.0 * beta / Re_D) ** 0.8
    if taps == "corner":
        L1 = L2p = 0.0
    elif taps == "flange":
        L1 = L2p = 0.0254 / D
    else:  # D-D/2
        L1, L2p = 1.0, 0.47
    M2p = 2.0 * L2p / (1.0 - beta)
    C = (
        0.5961
        + 0.0261 * beta**2
        - 0.216 * beta**8
        + 0.000521 * (1e6 * beta / Re_D) ** 0.7
        + (0.0188 + 0.0063 * A) * beta**3.5 * (1e6 / Re_D) ** 0.3
        + (0.043 + 0.080 * math.exp(-10.0 * L1) - 0.123 * math.exp(-7.0 * L1))
        * (1.0 - 0.11 * A)
        * beta**4
        / (1.0 - beta**4)
        - 0.031 * (M2p - 0.8 * M2p**1.1) * beta**1.3
    )
    if D * 1000.0 < 71.12:
        C += 0.011 * (0.75 - beta) * (2.8 - D * 1000.0 / 25.4)
    return C


def assert_close(measured: float, expected: float, tol_rel: float = 1e-10) -> None:
    assert measured == pytest.approx(expected, rel=tol_rel)


def test_o1_liquid_flange() -> None:
    """Spec O1: liquid, D = 0.10226, d = 0.05, flange taps, qm = 10 kg/s."""
    r = orifice_dp(10.0, 0.10226, 0.05, 998.0, 1e-3, 5e5, None, "flange")
    assert_close(r["Re_D"], 124510.027844237)
    assert_close(r["C"], 0.605255904072185)
    assert_close(r["epsilon"], 1.0)
    assert_close(r["dP"], 33445.8129428092)
    assert_close(r["permanent_loss"], 24852.9608421957)
    # Independent eq. (4) cross-check (agrees with fluids to the last digit).
    assert_close(
        r["C"],
        C_iso_eq4(0.10226, 0.05, 998.0, 1e-3, 10.0, "flange"),
        tol_rel=1e-12,
    )


def test_o2_gas_corner() -> None:
    """Spec O2: gas, D = 0.10226, d = 0.06, corner taps, qm = 1.5 kg/s."""
    r = orifice_dp(1.5, 0.10226, 0.06, 40.0, 1.2e-5, 5e6, 1.3, "corner")
    assert_close(r["Re_D"], 1556375.34805296)
    assert_close(r["C"], 0.604878186749537)
    assert_close(r["epsilon"], 0.999485073056371)
    assert_close(r["dP"], 8484.63326807909)
    assert_close(r["permanent_loss"], 5464.24065361060)
    assert_close(
        r["C"],
        C_iso_eq4(0.10226, 0.06, 40.0, 1.2e-5, 1.5, "corner"),
        tol_rel=1e-12,
    )


def test_o3_small_pipe_d_and_half() -> None:
    """Spec O3: D = 0.05 m brings in the D < 71.12 mm term; D-D/2 taps."""
    r = orifice_dp(2.0, 0.05, 0.025, 998.0, 1e-3, 5e5, None, "D-D/2")
    assert_close(r["Re_D"], 50929.5817894065)
    assert_close(r["C"], 0.610337411029475)
    assert_close(r["dP"], 20931.0469127572)
    assert_close(r["permanent_loss"], 15292.2601494554)
    assert_close(
        r["C"],
        C_iso_eq4(0.05, 0.025, 998.0, 1e-3, 2.0, "D-D/2"),
        tol_rel=1e-12,
    )


def test_liquid_below_pressure_limit() -> None:
    """Liquid refusal: implied dP >= P1 is refused."""
    with pytest.raises(OrificeR1Error, match="exceeds the inlet pressure"):
        orifice_dp(10.0, 0.10226, 0.05, 998.0, 1e-3, 3e4, None, "flange")


def test_gas_below_pressure_ratio_limit() -> None:
    """Gas refusal: P2/P1 < 0.75 is refused before the eps evaluation."""
    with pytest.raises(OrificeR1Error, match="P2/P1"):
        orifice_dp(1.5, 0.10226, 0.06, 40.0, 1.2e-5, 1e4, 1.3, "corner")


def test_validity_bore_too_small() -> None:
    """Validity refusal: d < 12.5 mm."""
    with pytest.raises(OrificeR1Error, match="outside ISO 5167-2 validity.*d"):
        orifice_dp(0.1, 0.10226, 0.01, 998.0, 1e-3, 5e5, None, "flange")


def test_validity_pipe_too_small() -> None:
    """Validity refusal: D < 50 mm."""
    with pytest.raises(OrificeR1Error, match="D_m.*outside ISO 5167-2 validity"):
        orifice_dp(0.1, 0.04, 0.02, 998.0, 1e-3, 5e5, None, "flange")


def test_validity_beta_out_of_range() -> None:
    """Validity refusal: beta > 0.75."""
    with pytest.raises(OrificeR1Error, match="outside ISO 5167-2 validity.*beta"):
        orifice_dp(0.1, 0.1, 0.078, 998.0, 1e-3, 5e5, None, "flange")


def test_validity_re_too_low_flange() -> None:
    """Validity refusal: flange-tap Re_D limit (170*beta^2*D in mm)."""
    # beta = 0.75, D = 100 mm -> flange limit 170*beta^2*D = 9562.5, above the
    # 5000 floor, so it binds; Re_D = 9000 is refused by it.
    qm = 9000.0 * math.pi * 0.1 * 1e-3 / 4.0
    with pytest.raises(OrificeR1Error, match="outside ISO 5167-2 validity.*Re_D"):
        orifice_dp(qm, 0.1, 0.075, 998.0, 1e-3, 5e5, None, "flange")


def test_bad_taps_refused() -> None:
    """Refusal: taps outside the catalogue enum."""
    with pytest.raises(OrificeR1Error, match="taps"):
        orifice_dp(10.0, 0.10226, 0.05, 998.0, 1e-3, 5e5, None, "venacontracta")


def test_bad_c_specified_refused() -> None:
    """Refusal: C_specified outside (0, 1)."""
    with pytest.raises(OrificeR1Error, match="C_specified"):
        orifice_dp(10.0, 0.10226, 0.05, 998.0, 1e-3, 5e5, None, "flange", 1.0)
